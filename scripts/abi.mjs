// Copies contract ABIs from the Foundry build into the SDK as typed constants.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const out = new URL("../contracts/out/", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const contracts = {
  riderMarketAbi: "RiderMarket.sol/RiderMarket.json",
  riderPoolAbi: "RiderPool.sol/RiderPool.json",
  riderPolicyAbi: "RiderPolicy.sol/RiderPolicy.json",
  riderFactoryAbi: "RiderFactory.sol/RiderFactory.json",
  riderTriggerAbi: "IRiderTrigger.sol/IRiderTrigger.json",
  canaryVaultAbi: "CanaryVault.sol/CanaryVault.json",
};

let src = "// Generated by scripts/abi.mjs from the Foundry build. Do not edit by hand.\n\n";
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(join(out, file), "utf8"));
  src += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
const target = new URL("../packages/sdk/src/abis.ts", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
writeFileSync(target, src);
console.log(`wrote ${Object.keys(contracts).length} ABIs to ${target}`);
